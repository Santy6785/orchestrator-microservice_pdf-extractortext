import logging
from typing import Any

from app.clients.base import BaseClient
from app.core.config import settings

logger = logging.getLogger(__name__)


class PersistenceClient(BaseClient):
    """Client for the persistence microservice.
    URL configurada vía ``PERSISTENCE_SERVICE_URL`` en la instancia central de
    ``Settings``.
    """

    def __init__(
        self,
        service_url: str = settings.persistence_service_url,
        timeout: float | None = None,
    ):
        if timeout is None:
            timeout = settings.persistence_timeout_seconds
        super().__init__(service_url=service_url, timeout=timeout)

    async def register_document(self, payload: dict[str, Any]) -> Any:
        """Create a new document record.
        Calls ``POST /api/v1/documents`` on the persistence service.
        The document ID is generated by the persistence service and returned
        in the response body (field ``id``).
        """
        return await self.post("/api/v1/documents", json=payload)

    async def validate_document(self, document_id: str) -> bool:
        """Validate checksum/duplicate status.
        Calls ``GET /api/v1/documents/{document_id}/validate``.
        """
        result = await self.get(f"/api/v1/documents/{document_id}/validate")
        return result.get("valid", False)

    async def check_duplicate_by_checksum(self, checksum: str) -> Any:
        """Check whether a document with the given checksum already exists.
        Calls ``GET /api/v1/documents/by-checksum/{checksum}`` on the persistence service.
        """
        return await self.get(f"/api/v1/documents/by-checksum/{checksum}")
